"""Real Kimi correction test with a seeded synthetic simulator-only fixture."""
import asyncio
import json
from pathlib import Path
import sys
import tempfile
import time

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/"src"))
from ai_tutor.context import build_context
from ai_tutor.kimi import KimiProvider
from ai_tutor.store import Store


async def main():
    provider = KimiProvider(ROOT)
    checked = await provider.probe()
    if not checked["available"]:
        raise RuntimeError("Reviewed real Kimi provider unavailable")
    with tempfile.TemporaryDirectory(prefix="correction-probe-", dir=ROOT/"runtime") as temporary:
        store = Store(Path(temporary)/"simulator.sqlite3", "simulator")
        try:
            learner = store.create_learner("Synthetic correction fixture")
            lid = learner["learner_id"]
            first = store.create_session(lid)
            old = store.event(lid, first["session_id"], "simulated", {"text": "模拟报告：第一次小车停车并亮绿灯成功"})
            old_mid = store.add_memory(lid, {"kind": "reported_progress", "content": "模拟报告第一次小车停车并亮绿灯成功", "scope": "current_activity", "source_event_ids": [old]}, 0)
            second = store.create_session(lid)
            text = "继续小车停车活动。刚才说错了，第一次并没有停下来，绿灯也没有亮。请更正之前那条停车成功的模拟报告，记住这是模拟结果，不能算实体硬件验证。"
            current = store.event(lid, second["session_id"], "simulated", {"text": text})
            context = build_context(store, second, learner, text, current, {})
            started = time.monotonic()
            reply = await provider.generate({"request_id": "source-linked-correction-probe", "learner_id": lid,
                "session_id": second["session_id"], "generation": 1, "context": context})
            elapsed = round((time.monotonic()-started)*1000)
            valid = {source["event_id"] for source in context["evidence"]}
            applied = []
            for candidate in reply["memory_candidates"]:
                if set(candidate["source_event_ids"]) <= valid:
                    result = store.add_memory(lid, candidate, 0)
                    if result:
                        applied.append(result)
            active = store.memories(lid)
            correction = next((memory for memory in active if memory["kind"] == "correction"), None)
            passed = bool(correction and old_mid in correction["supersedes"] and old_mid not in {memory["memory_id"] for memory in active})
            lines = ["# Real source-linked correction probe", "", "This developer integration probe uses a seeded synthetic simulator-only memory fixture. "
                     "The correcting reply is generated by actual authenticated Kimi Code 2.3.1 with the new bounded context builder. "
                     "No child/human observation, car execution, or camera action is claimed. Temporary fixture DB is removed after the test.", "",
                     f"Result: {'PASS' if passed else 'FAIL'}. Real call latency: {elapsed} ms. Context chars: {len(json.dumps(context, ensure_ascii=False))}.", "",
                     "Input: " + text, "", "Actual Kimi reply: " + reply["reply_text"], "",
                     "Actual memory candidates:", "", "```json", json.dumps(reply["memory_candidates"], ensure_ascii=False, indent=2), "```", "",
                     f"Applied candidates: {len(applied)}. Original active note excluded: {old_mid not in {memory['memory_id'] for memory in active}}. "
                     f"Correction source type: {correction['source_type'] if correction else 'none'}."]
            (ROOT/"docs/CORRECTION_REPORT.md").write_text("\n".join(lines), encoding="utf-8")
            print(json.dumps({"passed": passed, "latency_ms": elapsed, "reply_text": reply["reply_text"], "applied_count": len(applied)}, ensure_ascii=False))
            if not passed:
                raise RuntimeError("Real correction did not supersede linked old progress; see sanitized report")
        finally:
            store.close()
            await provider.close()


if __name__ == "__main__":
    asyncio.run(main())
